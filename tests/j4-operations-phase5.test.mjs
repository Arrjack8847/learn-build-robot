 assert.equal((await run("attendance",{...cmd("mark-present",5),reason:"\n bad"})).ok,false);
 const stale=get();q.reject(true);assert.equal((await run("attendance",cmd("mark-present",5))).status,"RETRY_REQUIRED");assert.deepEqual(get(),stale);q.reject(false);
 q.fail(true);await assert.rejects(()=>run("attendance",cmd("mark-present",5)),/transport/);assert.deepEqual(get(),stale);q.fail(false);
 const first=cmd("mark-present",5),r=await Promise.all([run("attendance",first),run("attendance",first)]);
 assert.equal(r.every(x=>x.ok),true);assert.equal(r[0].auditId,r[1].auditId);assert.equal(get().audit.filter(a=>a.requestId===first.requestId).length,1);
 assert.equal((await run("attendance",{...first,reason:"Different reason"})).ok,false);
