const admin="qa-j4-staff-1",staff="qa-j4-staff-2",finance="qa-j4-staff-3",day="2026-11-26";
const clone=x=>JSON.parse(JSON.stringify(x));
function setup(){
 let state={...createJ4Fixtures(),mode:"j4-fixture-v1",stateVersion:"start",learningVisits:[{studentId:"qa-j4-student-1",bookingId:"qa-j4-booking-1",sessionDate:day,status:"learning"}]},seq=0,code=10000000,at=Date.parse(day+"T12:00:00+08:00"),reject=false,fail=false;
 const store={readStrong:async()=>clone(state),compareAndSet:async(v,n)=>{if(fail)throw Error("transport");if(reject||state.stateVersion!==v)return false;state=clone(n);return true;}};
 const crypto={newId:()=>String(++seq).padStart(32,"0"),newCheckInCode:()=>String(++code),checkInDigest:(scope,c)=>scope+":"+c,equalDigest:(a,b)=>a===b};
 const clock={now:()=>at,localDay:()=>day};
 const service=id=>createJ4StateService({store,crypto,clock,fixtureActorId:id});
 const run=(action,input,id=staff)=>service(id)[action](null,input);
 const cmd=(action,n,req=action+"-"+n)=>({action,bookingId:"qa-j4-booking-"+n,requestId:"phase5-"+req,reason:"Fictional operation"});
 return {run,cmd,get:()=>clone(state),advance:ms=>at+=ms,edit:f=>f(state),reject:v=>reject=v,fail:v=>fail=v,clock};
}
