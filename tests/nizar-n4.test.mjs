import test from "node:test";
import assert from "node:assert/strict";
import {createSchedulingRepository} from "../scripts/nizar/repository.mjs";
import {createBookingService} from "../scripts/nizar/booking-service.mjs";
import {createN4Service} from "../scripts/nizar/automation-service.mjs";
import {depositBalance,monthlyNoShows} from "../scripts/nizar/automation-state.mjs";
import {NIZAR_BRANCH} from "../scripts/nizar/contract.mjs";
const env={VERCEL_ENV:"preview",VERCEL_TARGET_ENV:"preview",VERCEL_GIT_COMMIT_REF:NIZAR_BRANCH,NIZAR_SCHEDULING_ENABLED:"1"};
const id=n=>"qa-j2-"+n.toString(16).padStart(64,"0");
const base=Date.parse("2026-11-27T08:00:00+08:00");
const time=(d,h,m=0)=>Date.parse(d+"T"+String(h).padStart(2,"0")+":"+String(m).padStart(2,"0")+":00+08:00");
function setup(){
 let row=null,t=base;let attendance=true;const paid=new Map();
 const db={get:async()=>structuredClone(row),insert:async(c,k,v)=>{if(row)return false;row=structuredClone(v);return true},replaceIfVersion:async(c,k,e,v)=>{if(row?.stateVersion!==e)return false;row=structuredClone(v);return true}};
 const repository=createSchedulingRepository({env,db,clock:()=>t});
 const owner=c=>({childId:c,parentId:id(100),stateVersion:"v1"});
 const resolveChild=async(actor,c)=>actor===1?owner(c):null;
 const readEligibility=async o=>({membership:paid.get(o.childId)===false?"inactive":"active",deposit:"clear"});
 const deps={repository,resolveChild,readEligibility,clock:()=>t};
 const execute=createBookingService(deps),automation=createN4Service({...deps,readOwner:async(c,p)=>p===id(100)?owner(c):null,readAttendance:async b=>attendance?{bookingId:b.bookingId,revision:b.revision,status:"confirmed-no-attendance"}:null,verifyEvent:async e=>e?.verified===true?e:null});
 return {execute,automation,repository,now:()=>t,setTime:x=>t=x,paid,attendance:x=>attendance=x};
}
const book=(n,d="2026-11-27",h=10,a="robotics")=>({action:"book",childId:id(n),day:d,hour:h,activity:a,requestId:"request-book-"+n+"-"+d+"-"+h+"-"+a});
const event=(s,n,kind,extra={})=>({verified:true,eventId:"event-fixture-"+kind+"-"+n,kind,childId:id(n),parentId:id(100),at:s.now(),...extra});
test("no-show warning, second blocks, verified RM50, third forfeits, excusal and month reset",async()=>{
 const s=setup();
 for(const d of ["2026-11-27","2026-11-28","2026-11-29"])assert.equal((await s.execute(book(1,d),1)).ok,true);
 s.setTime(time("2026-11-27",11));s.attendance(false);await s.automation.tick();
 assert.equal(monthlyNoShows((await s.repository.read()).state,id(1),"2026-11"),0);
 s.attendance(true);assert.equal((await s.automation.tick()).ok,true);await s.automation.tick();
 s.setTime(time("2026-11-28",11));assert.equal((await s.automation.tick()).ok,true);
 let state=(await s.repository.read()).state;
 assert.equal(monthlyNoShows(state,id(1),"2026-11"),2);
 assert.equal(state.n4.notices.filter(x=>x.kind==="no-show-warning").length,1);
 assert.equal((await s.execute(book(1,"2026-11-30"),1)).status,"DEPOSIT_REQUIRED");
 const payment=event(s,1,"deposit-paid",{currency:"MYR",amount:5000,paymentId:"payment-fixture-1"});
 assert.equal((await s.automation.event({...payment,verified:false})).status,"UNVERIFIED_EVENT");
 assert.equal((await s.automation.event(payment)).ok,true);assert.equal((await s.automation.event(payment)).status,"ALREADY_COMMITTED");
 assert.equal((await s.execute(book(1,"2026-11-30"),1)).ok,true);
 s.setTime(time("2026-11-29",11));assert.equal((await s.automation.tick()).ok,true);
 state=(await s.repository.read()).state;assert.equal(depositBalance(state,id(1),"2026-11").held,0);
 assert.equal((await s.execute(book(1,"2026-12-01"),1)).status,"DEPOSIT_REQUIRED");
 const b=state.bookings.find(x=>x.day==="2026-11-30");
 assert.equal((await s.automation.event(event(s,1,"excuse",{bookingId:b.bookingId,staffId:"staff-fixture-001",reason:"Lab closed"}))).ok,true);
 s.setTime(time("2026-12-01",8));await s.automation.tick();
 assert.equal((await s.execute(book(1,"2026-12-01"),1)).ok,true);
});
test("unpaid hold expires at 24 hours, duplicate cannot extend, future seats released",async()=>{
 const s=setup();assert.equal((await s.execute(book(2,"2026-11-29"),1)).ok,true);
 const failed=event(s,2,"renewal-failed",{cycleId:"renewal-cycle-001"});
 assert.equal((await s.automation.event(failed)).ok,true);
 assert.equal((await s.execute(book(2,"2026-11-30"),1)).status,"MEMBERSHIP_REQUIRED");
 s.setTime(base+3600000);assert.equal((await s.automation.event({...failed,eventId:"event-duplicate-0001",at:s.now()})).status,"ALREADY_COMMITTED");
 s.setTime(base+86400000-1);await s.automation.tick();assert.equal((await s.repository.read()).state.bookings[0].bookingStatus,"held-unpaid");
 s.setTime(base+86400000);await s.automation.tick();assert.equal((await s.repository.read()).state.bookings[0].bookingStatus,"cancelled");
});
test("FIFO waitlist reserves capacity, offer expires at 30 minutes, next parent accepts atomically",async()=>{
 const s=setup(),d="2026-11-28";
 for(let n=1;n<=5;n++)assert.equal((await s.execute(book(n,d),1)).ok,true);
 const join=n=>({action:"waitlist-join",childId:id(n),day:d,hour:10,activity:"robotics",requestId:"wait-fixture-"+n+"-0001"});
 const a=await s.automation.waitlist(join(6),1);assert.equal(a.ok,true);
 s.setTime(base+1);const b=await s.automation.waitlist(join(7),1);assert.equal(b.ok,true);
 const first=(await s.repository.read()).state.bookings[0];
 assert.equal((await s.execute({action:"cancel",childId:first.childId,bookingId:first.bookingId,revision:first.revision,requestId:"cancel-fixture-001"},1)).ok,true);
 assert.equal((await s.execute(book(8,d),1)).status,"SLOT_FULL");
 await s.automation.tick();
 let state=(await s.repository.read()).state;const offer=state.n4.waitlist.find(x=>x.id===a.entry.id);assert.equal(offer.status,"offered");
 assert.equal((await s.automation.waitlist({action:"waitlist-accept",childId:id(7),offerId:offer.id},1)).status,"NOT_AUTHORIZED");
 s.setTime(offer.expiresAt);await s.automation.tick();state=(await s.repository.read()).state;
 assert.equal(state.n4.waitlist.find(x=>x.id===a.entry.id).status,"expired");
 assert.equal(state.n4.waitlist.find(x=>x.id===b.entry.id).status,"offered");
 assert.equal((await s.automation.waitlist({action:"waitlist-accept",childId:id(7),offerId:b.entry.id},1)).ok,true);
 assert.equal((await s.automation.waitlist({action:"waitlist-accept",childId:id(7),offerId:b.entry.id},1)).status,"ALREADY_COMMITTED");
 assert.equal((await s.repository.read()).state.bookings.filter(x=>x.bookingStatus==="booked").length,5);
});
test("month-end cash refund is owed until verified receipt, not auto-paid",async()=>{
 const s=setup();
 for(const d of ["2026-11-27","2026-11-28"])assert.equal((await s.execute(book(1,d),1)).ok,true);
 s.setTime(time("2026-11-28",11));await s.automation.tick();
 assert.equal((await s.automation.event(event(s,1,"deposit-paid",{currency:"MYR",amount:5000,paymentId:"payment-fixture-2"}))).ok,true);
 s.setTime(time("2026-12-01",8));await s.automation.tick();await s.automation.tick();
 assert.deepEqual(depositBalance((await s.repository.read()).state,id(1),"2026-11"),{held:0,due:5000});
 const refund=event(s,1,"refund-recorded",{month:"2026-11",staffId:"staff-fixture-002",receiptId:"receipt-fixture-001",currency:"MYR",amount:5000});
 assert.equal((await s.automation.event(refund)).ok,true);assert.equal((await s.automation.event(refund)).status,"ALREADY_COMMITTED");
 assert.deepEqual(depositBalance((await s.repository.read()).state,id(1),"2026-11"),{held:0,due:0});
});
