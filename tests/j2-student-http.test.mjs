import test from "node:test";
import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {createStudentAuthHttp} from "../scripts/student-auth/http.mjs";
import {createStudentContext} from "../scripts/student-auth/session-context.mjs";
import {createAuthCrypto} from "../scripts/parent-auth/secure-auth-transport.mjs";
import {createStudentAuthCrypto} from "../scripts/student-auth/crypto.mjs";
import {createFamilyPreview,NOTICE_VERSION} from "../scripts/parent-auth/family-preview.mjs";
test("J2 HTTP route: private gate, CSRF, input limits, actual OTP/PIN session, replay and logout",async()=>{
 const env={VERCEL_ENV:"preview",VERCEL_URL:"j2.invalid",STUDENT_AUTH_ENABLED:"true",PARENT_AUTH_SECRET:randomBytes(32).toString("hex"),STUDENT_AUTH_SECRET:randomBytes(32).toString("hex")};
 const email="a@example.invalid",emails=[email],clock={now:()=>1795660000000},rows=new Map(),sent=new Map(),key=(c,id)=>c+":"+id;
 const db={get:async(c,id)=>structuredClone(rows.get(key(c,id))??null),insert:async(c,id,r)=>{if(rows.has(key(c,id)))return false;rows.set(key(c,id),structuredClone(r));return true;},replaceIfVersion:async(c,id,v,r)=>{if(rows.get(key(c,id))?.stateVersion!==v)return false;rows.set(key(c,id),structuredClone(r));return true;},listFixtureChildren:async p=>[...rows.entries()].filter(([k,r])=>k.startsWith("Children:")&&r.parentId===p).map(([,r])=>structuredClone(r))};
 const auth=createAuthCrypto(env),crypto=createStudentAuthCrypto(env);
 const context=createStudentContext({db,auth,crypto,clock,emails,mailerFor:recipient=>({sendParentCode:async(to,code)=>{assert.equal(to,recipient);sent.set(to,code);}})});
 const handle=createStudentAuthHttp({resolveContext:async()=>({db,emails,context})});
 const call=async(action,body,cookies="",changes={})=>{
  const headers={origin:"https://j2.invalid","sec-fetch-site":"same-origin","x-stem-student-auth":"1",...(cookies?{cookie:cookies}:{}),...(body?{"content-type":"application/json"}:{}),...changes.headers};
  const request=new Request("https://j2.invalid/api/dev/student-auth/"+action,{method:"POST",headers,...(body?{body:JSON.stringify(body)}:{})});
  const response=await handle(request,{...env,...changes.env});
  return {status:response.status,body:await response.json(),cookies:response.headers.getSetCookie()};
 };
 const token=(r,name)=>r.cookies.find(x=>x.startsWith(name+"="))?.split(";")[0];
 assert.equal((await call("status",null,"",{env:{VERCEL_ENV:"production"}})).status,404);
 assert.equal((await call("status",null,"",{env:{STUDENT_AUTH_ENABLED:"false"}})).status,503);
 assert.equal((await call("status",null,"",{headers:{origin:"https://other.invalid"}})).status,403);
 assert.equal((await call("request",{email:"a".repeat(600)})).status,400);
 assert.equal((await call("request",{email:"other@example.invalid"})).status,403);
 assert.equal((await call("list")).status,401);
 const payerSvc=context.svc(email,false);await payerSvc.requestCode();const payer=await payerSvc.verifyCode(sent.get(email));
 const family=createFamilyPreview({db,crypto:auth,clock,resolveSession:t=>payerSvc.resolveIdentity(t)});
 await family.handle(payer.token,"family-consent",{accepted:true,noticeVersion:NOTICE_VERSION});
 const registration=await family.handle(payer.token,"family-child-create",{name:"Test Student",birthYear:2018,requestKey:"aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa"});
 const studentId=registration.child.id,payerCookie="__Host-bsr-parent-test="+payer.token;
 assert.equal((await call("enrollment-status",{studentId},payerCookie)).body.status,"PIN_SETUP_REQUIRED");
 assert.equal((await call("enroll",{studentId,pin:"581304"},payerCookie)).body.status,"ENROLLED");
 assert.equal((await call("enrollment-status",{studentId},payerCookie)).body.status,"PIN_ALREADY_SET");
 assert.equal((await call("request",{email})).body.status,"CODE_SENT");
 assert.equal((await call("request",{email})).status,429);
 const code=sent.get(email),verification=await call("verify",{email,code});
 assert.equal(verification.body.status,"EMAIL_VERIFIED");assert.equal(verification.body.token,undefined);
 assert.match(verification.cookies[0],/HttpOnly; SameSite=Strict/);
 assert.equal((await call("verify",{email,code})).status,400);
 const proof=token(verification,"__Host-bsr-student-proof");
 assert.equal((await call("list",null,proof)).body.students[0].id,studentId);
 assert.equal((await call("enrollment-status",{studentId},proof)).status,403);
 assert.equal((await call("sign-in",{studentId,pin:"777777"},proof)).status,401);
 const login=await call("sign-in",{studentId,pin:"581304"},proof+"; "+payerCookie);
 assert.equal(login.body.status,"VERIFIED");assert.equal(login.body.token,undefined);
 const student=token(login,"__Host-bsr-student");assert.ok(student);
 assert.equal((await call("status",null,student)).body.student.id,studentId);
 assert.equal((await payerSvc.status(payer.token)).status,"NOT_VERIFIED");
 assert.equal((await call("list",null,proof)).status,401);
 assert.equal((await call("enroll",{studentId,pin:"723819"},student)).status,403);
 assert.equal((await call("logout",null,student)).body.status,"SIGNED_OUT");
 assert.equal((await call("status",null,student)).body.status,"NOT_VERIFIED");
});
