export type SyllabusLevelNumber = 1 | 2 | 3 | 4 | 5 | 6;
export type AdvancedLevelNumber = 2 | 3 | 4 | 5 | 6;
export type SyllabusProjectEntry = {
  id: string;
  name: string;
  sourceEntry: string;
  sourceKind: "folder" | "pdf" | "pptx";
};
export type SyllabusCategory = {
  id: string;
  name: string;
  entries: SyllabusProjectEntry[];
};
export const syllabusSlug = (name: string) => name.toLowerCase()
  .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export function getAdvancedLevel(level: number): SyllabusCategory[] {
  if (!Number.isInteger(level) || level < 2 || level > 6) return [];
  // Each syllabus category has a required title followed by zero or more entries.
  // A nonempty tuple preserves that invariant under noUncheckedIndexedAccess.
  const categories: ReadonlyArray<readonly [string, ...string[]]> = ADVANCED_SYLLABUS[level as AdvancedLevelNumber];
  return categories.map(([categoryName, ...sourceEntries]) => ({
    id: syllabusSlug(categoryName),
    name: categoryName,
    entries: sourceEntries.map((sourceEntry, index) => {
      const extension = /\.(pdf|pptx)$/i.exec(sourceEntry)?.[1]?.toLowerCase() as "pdf" | "pptx" | undefined;
      const name = extension ? sourceEntry.slice(0, -extension.length - 1) : sourceEntry;
      return {
        id: `${syllabusSlug(categoryName)}-${syllabusSlug(name)}-${index + 1}`,
        name,
        sourceEntry,
        sourceKind: extension ?? "folder",
      };
    }),
  }));
}

export function getLevelTotals(level: number): { categories: number; entries: number } {
  const categories = getAdvancedLevel(level);
  return { categories: categories.length, entries: categories.reduce((sum, cat) => sum + cat.entries.length, 0) };
}
