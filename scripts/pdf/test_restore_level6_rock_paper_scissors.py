#!/usr/bin/env python3
"""Offline regression for Level 6 page-14 Chinese-label restoration.

Runs only against an autogenerated synthetic PDF, never student content.
No GitHub Actions. Usage:
  python scripts/pdf/test_restore_level6_rock_paper_scissors.py
"""
from __future__ import annotations
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path
import fitz

SCRIPT = Path(__file__).with_name('restore_level6_rock_paper_scissors.py')
CHINESE = ['大型马达', 'AI模块', '中型马达', '大型马达', '控制器']
ENGLISH = ['Large Motor', 'AI Module', 'Medium Motor', 'Large Motor', 'Controller']

def pixels(page: fitz.Page) -> str:
    return hashlib.sha256(page.get_pixmap(alpha=False).samples).hexdigest()

def main() -> None:
    with tempfile.TemporaryDirectory(prefix='level6-restoration-test-') as d:
        work = Path(d)
        original, output, qa = work/'synthetic-original.pdf', work/'synthetic-english.pdf', work/'qa'
        doc=fitz.open()
        for i in range(14):
            page=doc.new_page(width=842,height=596)
            page.draw_rect(fitz.Rect(20,20,820,576),color=(.2,.2,.2),width=2)
            page.insert_text((32,40),f'Preserve this English title - page {i+1}',fontsize=12)
            if i==13:
                for j,zh in enumerate(CHINESE):
                    y=110+j*65
                    page.draw_line((85,y-8),(130,y-8),color=(0,0,1),width=1.2)
                    page.draw_circle((72,y-8),11,color=(0,.5,.5),width=2)
                    page.insert_text((145,y),zh,fontname='china-s',fontsize=11)
                    page.draw_line((205,y-8),(270,y-8),color=(1,0,0),width=2)
                    page.draw_rect(fitz.Rect(270,y-20,370,y+5),color=(0,.4,0),width=1)
        doc.save(original)
        doc.close()
        base=fitz.open(original)
        images=[pixels(p) for p in base]
        dims=[tuple(p.rect) for p in base]
        base.close()
        cmd=[sys.executable,str(SCRIPT),'--input',str(original),'--output',str(output),'--qa-dir',str(qa)]
        rejected=subprocess.run(cmd,capture_output=True,text=True)
        assert rejected.returncode!=0, 'Unverified source should be rejected'
        assert 'Unexpected source SHA' in rejected.stderr,rejected.stderr
        assert not output.exists(), 'Refused execution must not write a PDF'
        accepted=subprocess.run(cmd+['--allow-unverified-input'],capture_output=True,text=True)
        assert accepted.returncode==0,accepted.stderr
        cleaned=fitz.open(output)
        assert len(cleaned)==14
        assert [tuple(p.rect) for p in cleaned]==dims
        assert [pixels(cleaned[i]) for i in range(13)]==images[:13]
        text=cleaned[13].get_text()
        assert all(zh not in text for zh in CHINESE),repr(text)
        for en in set(ENGLISH):
            assert text.count(en)==ENGLISH.count(en),(en,text)
        assert 'Preserve this English title' in text
        for name in ('rock-paper-scissors-page14-before.png','rock-paper-scissors-page14-after.png','rock-paper-scissors-page14-manifest.json'):
            assert (qa/name).is_file(),name
        print('PASS: original-source hash guard rejects synthetic input')
        print('PASS: five labels translated; existing English retained')
        print('PASS: 14 page sizes retained; 13 untouched pages raster identical')
        print('PASS: QA before/after PNGs and JSON manifest emitted')

if __name__=='__main__':
    main()
